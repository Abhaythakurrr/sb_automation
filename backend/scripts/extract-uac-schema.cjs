/**
 * Distils openapi.json into a small, committable artifact.
 *
 * Run:  node scripts/extract-uac-schema.cjs [path/to/openapi.json]
 * Out:  src/copilot/knowledge/uacSchema.generated.json
 *
 * openapi.json is the vendor's full REST spec — 1.2 MB and gitignored, so it is
 * not present in a fresh clone. Rather than depend on it at runtime, this script
 * extracts only what the Copilot needs (field names per object type, plus the
 * endpoint list) into an artifact small enough to commit. The Copilot then works
 * everywhere, and this script is re-run when the controller is upgraded.
 */
const fs = require('fs');
const path = require('path');

const specPath = process.argv[2] || path.join(__dirname, '..', '..', 'openapi.json');
const outPath = path.join(__dirname, '..', 'src', 'copilot', 'knowledge', 'uacSchema.generated.json');

if (!fs.existsSync(specPath)) {
  console.error(`openapi.json not found at ${specPath}`);
  console.error('Pass the path explicitly: node scripts/extract-uac-schema.cjs /path/to/openapi.json');
  process.exit(1);
}

const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));
const schemas = spec.components?.schemas || {};

/** Resolves allOf inheritance into a flat property map. */
function flatten(name, seen = new Set()) {
  if (seen.has(name)) return { props: {}, parents: [] };
  seen.add(name);
  const node = schemas[name];
  if (!node) return { props: {}, parents: [] };

  const props = {};
  const parents = [];

  const walk = (n, depth = 0) => {
    if (!n || depth > 8) return;
    for (const part of n.allOf || []) {
      if (part.$ref) {
        const ref = part.$ref.split('/').pop();
        parents.push(ref);
        const inner = flatten(ref, seen);
        Object.assign(props, inner.props);
      } else {
        walk(part, depth + 1);
      }
    }
    for (const [k, v] of Object.entries(n.properties || {})) {
      props[k] = {
        type: v.type || (v.$ref ? 'object' : 'unknown'),
        ...(v.enum ? { enum: v.enum } : {}),
        ...(v.format ? { format: v.format } : {}),
      };
    }
  };
  walk(node);
  return { props, parents };
}

/**
 * The object types this application creates or reads. The spec defines 71 task
 * schemas; carrying all of them would bloat the artifact for no benefit.
 */
const TASK_TYPES = {
  taskUnix: 'TaskUnixWsData',
  taskWindows: 'TaskWindowsWsData',
  taskUcmd: 'TaskUcmdWsData',
  taskUniversal: 'TaskUniversalWsData',
  taskUniversalMonitor: 'TaskUniversalMonitorWsData',
  taskIbmi: 'TaskIbmiWsData',
  taskZos: 'TaskZosWsData',
  taskSql: 'TaskSQLWsData',
  taskStoredProc: 'TaskStoredProcWsData',
  taskFtp: 'TaskFtpWsData',
  taskSap: 'TaskSapWsData',
  taskPeoplesoft: 'TaskPeoplesoftWsData',
  taskFileMonitor: 'TaskFileMonitorWsData',
  taskSystemMonitor: 'TaskSystemMonitorWsData',
  taskVariableMonitor: 'TaskVariableMonitorWsData',
  taskWorkflow: 'TaskWorkflowWsData',
  taskSleep: 'TaskSleepWsData',
  taskEmail: 'TaskEmailWsData',
  taskWebService: 'TaskWebServiceWsData',
};

const TRIGGER_TYPES = {
  triggerTime: 'TriggerTimeWsData',
  triggerCron: 'TriggerCronWsData',
  triggerManual: 'TriggerManualWsData',
  triggerTemp: 'TriggerTempWsData',
  triggerFileMonitor: 'TriggerFmWsData',
  triggerTaskMonitor: 'TriggerTmWsData',
  triggerVariableMonitor: 'TriggerVmWsData',
  triggerEmailMonitor: 'TriggerEmWsData',
};

const out = {
  source: 'openapi.json',
  api: spec.info?.title || 'UAC REST API',
  controllerVersion: spec.info?.version || 'unknown',
  openapi: spec.openapi || spec.swagger,
  extractedAt: new Date().toISOString().slice(0, 10),
  note: 'Generated by backend/scripts/extract-uac-schema.cjs. Do not edit by hand.',
  endpoints: [],
  tasks: {},
  triggers: {},
  missingSchemas: [],
};

// Endpoints, with the methods each supports.
for (const [p, ops] of Object.entries(spec.paths || {})) {
  const methods = Object.keys(ops)
    .filter(m => ['get', 'post', 'put', 'delete', 'patch'].includes(m))
    .map(m => m.toUpperCase());
  if (methods.length) out.endpoints.push({ path: p, methods });
}
out.endpoints.sort((a, b) => a.path.localeCompare(b.path));

const addType = (bucket, key, schemaName) => {
  if (!schemas[schemaName]) { out.missingSchemas.push(`${key} -> ${schemaName}`); return; }
  const { props, parents } = flatten(schemaName);
  bucket[key] = {
    schema: schemaName,
    inherits: [...new Set(parents)],
    fields: Object.keys(props).sort(),
    // Keep type info only where it is not the default string, to stay compact.
    types: Object.fromEntries(
      Object.entries(props)
        .filter(([, v]) => v.type && v.type !== 'string')
        .map(([k, v]) => [k, v.type]),
    ),
    enums: Object.fromEntries(
      Object.entries(props).filter(([, v]) => v.enum).map(([k, v]) => [k, v.enum]),
    ),
  };
};

for (const [k, s] of Object.entries(TASK_TYPES)) addType(out.tasks, k, s);
for (const [k, s] of Object.entries(TRIGGER_TYPES)) addType(out.triggers, k, s);

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, JSON.stringify(out, null, 1));

const kb = (fs.statSync(outPath).size / 1024).toFixed(0);
console.log(`Controller ${out.controllerVersion} (OpenAPI ${out.openapi})`);
console.log(`  endpoints      : ${out.endpoints.length}`);
console.log(`  task types     : ${Object.keys(out.tasks).length}`);
console.log(`  trigger types  : ${Object.keys(out.triggers).length}`);
if (out.missingSchemas.length) console.log(`  not in spec    : ${out.missingSchemas.join(', ')}`);
console.log(`  taskUnix fields: ${out.tasks.taskUnix?.fields.length ?? 0}`);
console.log(`  triggerTime    : ${out.triggers.triggerTime?.fields.length ?? 0}`);
console.log(`  written        : ${outPath} (${kb} KB)`);
